const ALL_PRESETS: readonly BattleFormat[] = [...PRESETS, OPEN_LAB];

export function listPresets(): BattleFormat[] {
  return ALL_PRESETS.map(cloneFormat);
}

export function presetById(id: string): BattleFormat | undefined {
  const found = ALL_PRESETS.find((format) => format.id === id);
  return found ? cloneFormat(found) : undefined;
}

export function isPresetId(id: string): boolean {
  return ALL_PRESETS.some((format) => format.id === id);
}
